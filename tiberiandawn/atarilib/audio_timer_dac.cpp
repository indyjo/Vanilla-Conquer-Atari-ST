int Timer_Dac_Init(StAudioDriver sink)
{
	if (sink != ST_AUDIO_YM && sink != ST_AUDIO_COVOX) {
		return 0;
	}
	Timer_Dac_Shutdown();

	g_ring_mem = (unsigned char*)malloc((size_t)TIMER_DAC_RING_BYTES + (size_t)RING_ALIGN);
	if (!g_ring_mem) {
		printf("Timer-DAC: ring alloc failed\n");
		fflush(stdout);
		return 0;
	}
	{
		unsigned long const raw = (unsigned long)g_ring_mem;
		unsigned char* const aligned =
		    (unsigned char*)((raw + (unsigned long)RING_ALIGN - 1UL) & ~((unsigned long)RING_ALIGN - 1UL));
		memset(aligned, 0, (size_t)TIMER_DAC_RING_BYTES);
		g_play = aligned;
		digi_ring_init(&g_ring, aligned, TIMER_DAC_RING_BYTES, &g_timer_ops);
	}

	g_sink = sink;
	ym_build_lut();

	/*
	 * cnc.tos stays supervisor after startup Super(0); do not nest Super(0)/Super(ssp)
	 * (that drops to user mode and the next $FFFF8800 write bus-errors).
	 */
	ym_chip_claim();
	g_saved_iera = *((volatile unsigned char*)MFP_IERA);
	g_saved_imra = *((volatile unsigned char*)MFP_IMRA);
	g_saved_tacr = *((volatile unsigned char*)MFP_TACR);
	g_old_timera = *(void (**)(void))MFP_VEC_TIMERA;
	g_stride = 1u;
	timer_install_active_isr();

	g_movie_owner = 0;
	g_paused = 1;
	g_inited = 1;
	return 1;
}

void Timer_Dac_Shutdown(void)
{
	if (!g_inited && !g_ring_mem) {
		g_sink = ST_AUDIO_NONE;
		return;
	}
	timer_stop(&g_ring);
	if (g_old_timera) {
		*(void (**)(void))MFP_VEC_TIMERA = g_old_timera;
	}
	*((volatile unsigned char*)MFP_IERA) = g_saved_iera;
	*((volatile unsigned char*)MFP_IMRA) = g_saved_imra;
	*((volatile unsigned char*)MFP_TACR) = g_saved_tacr;
	ym_chip_restore();

	free(g_ring_mem);
	g_ring_mem = 0;
	g_play = 0;
	digi_ring_reset(&g_ring);
	g_ring.base = 0;
	g_sink = ST_AUDIO_NONE;
	g_inited = 0;
	g_old_timera = 0;
}

DigiRing* Timer_Dac_Ring(void)
{
	return g_inited ? &g_ring : 0;
}

DigiRingOps const* Timer_Dac_Ops(void)
{
	return &g_timer_ops;
}

void Timer_Dac_Set_Stride(unsigned stride)
{
	g_stride = stride >= 2u ? 2u : 1u;
	digi_ring_set_stride(&g_ring, g_stride);
	if (g_inited) {
		timer_install_active_isr();
	}
}

void Timer_Dac_Set_Movie_Owner(int movie_owns)
{
	g_movie_owner = movie_owns ? 1 : 0;
	Timer_Dac_Set_Stride(movie_owns ? 2u : 1u);
}

void Timer_Dac_Pause(void)
{
	timer_stop(&g_ring);
	g_ring.armed = 0;
}

void Timer_Dac_Resume(void)
{
	g_paused = 0;
}

void Timer_Dac_Game_Arm(unsigned prefill)
{
	if (!g_inited || !g_ring.base) {
		return;
	}
	Timer_Dac_Set_Movie_Owner(0);
	g_ring.write_pos = prefill % g_ring.size;
	g_ring.queued = prefill;
	g_ring.last_consumer = 0;
	g_play = g_ring.base;
	timer_arm(&g_ring);
	g_ring.armed = 1;
}

void Timer_Dac_Game_Stop(void)
{
	Timer_Dac_Pause();
	digi_ring_reset(&g_ring);
	if (g_ring.base) {
		memset(g_ring.base, 0, g_ring.size);
	}
}

int Timer_Dac_Active(void)
{
	return g_inited && g_timer_on && !g_paused;
}

int Timer_Dac_Movie_Owns(void)
{
	return g_movie_owner;
}

