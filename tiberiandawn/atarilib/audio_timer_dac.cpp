/*
 * audio_timer_dac.cpp - MFP Timer A ~6.25 kHz digi (YM movep LUT / Covox Port B).
 *
 * Soft 1024-byte ring (TT-RAM OK), **2048-byte aligned**, holds signed STE-style PCM
 * (0 = silence). Play cursor is one fused 32-bit address (base|offset): ISR advances
 * with (a0)+ and andi.w on the low word (mask 0xFBFF). YM: 64×8 LUT from Ray
 * da_table centers; ^0x80 baked as slot i ← Ray[(i^0x20)<<2|+2]. ISR: andi/add.
 * Covox: Port B movep.w $0F|sample. Four specialized ISRs (YM/Covox × stride 1/2).
 */
